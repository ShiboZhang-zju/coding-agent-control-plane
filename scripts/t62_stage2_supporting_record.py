"""Generate the T62 stage 2 supporting record from the ledgers and transcripts.

The main acceptance file answers "did the required facts hold". This one keeps
the *behavioural* detail - how many files each arm read, what it edited, how
long it ran - because that is what a reader needs to judge whether memory was
actually used, and it must be derived, not narrated.

Raw transcripts are not committed (absolute workspace paths). Only counts, file
names and the arm-level observations are kept.
"""
from __future__ import annotations

import json
import sqlite3
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from adapters.codebuddy.client import Api  # noqa: E402
from sanitize_evidence import write_evidence  # noqa: E402

STATE = ROOT / ".poc-state" / "t62"
PILOT = STATE / "stage2.db"
CONTRAST = STATE / "stage2c.db"
OUT = ROOT / "evidence" / "project" / "T62-stage2-pilot-transcripts.json"
BASE = "http://127.0.0.1:8787"

ARMS = {
    "A": (PILOT, "cp-50dc18149ac2", "fix parsing.py boundaries"),
    "B_rejected": (PILOT, "cp-570efa369576",
                   "follow-up in metrics.py; committed outside its worktree"),
    "B": (PILOT, "cp-5a2bd464ca89", "follow-up in metrics.py, memory present"),
    "C1": (CONTRAST, "cp-69d3691973ed", "controlled contrast WITH memory"),
    "C0": (CONTRAST, "cp-133a8c27b707", "controlled contrast WITHOUT memory"),
}


def ro(ledger: Path, sql: str, args: tuple = ()) -> list[dict]:
    conn = sqlite3.connect(f"file:{ledger}?mode=ro", uri=True, timeout=20)
    conn.row_factory = sqlite3.Row
    try:
        return [dict(r) for r in conn.execute(sql, args).fetchall()]
    finally:
        conn.close()


def stats(job_prefix: str) -> dict:
    api = Api(base=BASE)
    api.login()
    offset, updates = 0, []
    while True:
        r = api.job_transcript(job_prefix, offset=offset, limit=60)
        chunk = ((r.get("body") or {}).get("data") or {}).get("updates") or []
        if not chunk:
            break
        updates.extend(chunk)
        offset += len(chunk)
        if len(chunk) < 60:
            break

    reads, edits, commands = [], [], []
    for u in updates:
        if u.get("sessionUpdate") != "tool_call":
            continue
        raw = u.get("rawInput") or {}
        title = (u.get("title") or "").split(" ")[0]
        if title == "Read":
            reads.append(Path(str(raw.get("file_path", ""))).name)
        elif title in ("Edit", "Write", "MultiEdit"):
            edits.append(Path(str(raw.get("file_path", ""))).name)
        if raw.get("command"):
            commands.append(str(raw["command"])[:200])
    return {
        "tool_calls": len(reads) + len(edits) + len(commands),
        "reads": sorted(set(reads)),
        "edits": sorted(set(edits)),
        "shell_commands": commands,
    }


def main() -> int:
    if not PILOT.exists() or not CONTRAST.exists():
        write_evidence(OUT, {
            "test": "T62 stage 2 supporting record",
            "result": "BLOCKED",
            "blocked_reason": "pilot or contrast ledger missing",
        })
        return 2

    arms = {}
    for label, (ledger, tid, purpose) in ARMS.items():
        rows = ro(ledger, "select * from work_items where id=?", (tid,))
        refs = ro(ledger, "select * from session_references where work_item_id=?",
                  (tid,))
        if not rows:
            arms[label] = {"error": "task not in ledger"}
            continue
        task = rows[0]
        session = (refs[0]["session_id"] if refs else "") or ""
        detail = stats(session[:8]) if session else {"error": "no session"}
        arms[label] = {
            "task_id": tid,
            "purpose": purpose,
            "verdict": task["verdict"],
            "state": task["state"],
            "context_version": task["context_version"],
            "duration_s": (round(task["finished_at"] - task["started_at"], 1)
                           if task.get("finished_at") and task.get("started_at")
                           else None),
            "prompt_chars": len(task.get("effective_prompt") or ""),
            **detail,
        }

    c1, c0 = arms.get("C1", {}), arms.get("C0", {})
    record = {
        "test": "T62 stage 2 supporting record: worker behaviour per arm",
        "derived_from": [
            "stage2.db (pilot ledger)",
            "stage2c.db (contrast ledger)",
            "CodeBuddy job transcripts at the local service",
        ],
        "note": ("Generated by scripts/t62_stage2_supporting_record.py. Raw "
                 "transcripts are not committed; only counts, file names and "
                 "shell commands are kept. No value here is estimated."),
        "arms": arms,
        "contrast_reading": {
            "c1_reads": len(c1.get("reads") or []),
            "c0_reads": len(c0.get("reads") or []),
            "c1_tool_calls": c1.get("tool_calls"),
            "c0_tool_calls": c0.get("tool_calls"),
            "c1_duration_s": c1.get("duration_s"),
            "c0_duration_s": c0.get("duration_s"),
            "c1_extra_files_vs_c0": sorted(set(c1.get("reads") or [])
                                           ^ set(c0.get("reads") or [])),
            "interpretation": (
                "Both arms reached the same verdict. The memory-free arm read one "
                "extra test file and took slightly longer. With one pair this is "
                "consistent with, but does not demonstrate, the injected rule "
                "saving exploration."),
            "is_statistical_claim": False,
        },
        "usage_availability": {
            "worker_reports_token_usage": False,
            "detail": ("Every token/cost field the CodeBuddy job API returns is "
                       "null for all five sessions, so token usage is recorded as "
                       "unavailable rather than estimated."),
        },
    }
    write_evidence(OUT, record)
    print(json.dumps({"result": "PASS", "arms": list(arms)}, ensure_ascii=False))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
